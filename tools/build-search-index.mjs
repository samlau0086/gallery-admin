import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const productsDir = path.resolve('src/content/products');
const outputPath = path.resolve('src/data/search-index.ts');
const parseScalar = (value = '') => {
  const trimmed = value.trim();
  if (!trimmed) return '';
  try { return JSON.parse(trimmed); } catch { return trimmed.replace(/^['"]|['"]$/g, ''); }
};
const files = (await readdir(productsDir)).filter((file) => file.endsWith('.md'));
const records = [];
for (const file of files) {
  const source = await readFile(path.join(productsDir, file), 'utf8');
  const frontmatter = source.match(/^---\s*\n([\s\S]*?)\n---/m)?.[1] ?? '';
  const get = (key) => parseScalar(frontmatter.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'))?.[1]);
  const tags = parseScalar(frontmatter.match(/^tags:\s*(.+)$/m)?.[1]);
  if (get('published') === false || get('published') === 'false') continue;
  const slug = file.replace(/\.md$/, '');
  const title = get('title'); const titleZh = get('titleZh'); const category = get('category');
  const sku = get('sku'); const brand = get('brand'); const cover = get('cover');
  const sortOrder = Number(get('sortOrder')) || 0;
  const searchable = [title, titleZh, category, brand, sku, ...(Array.isArray(tags) ? tags : [])].filter(Boolean).join(' ').toLowerCase();
  records.push({ slug, title, titleZh, category, brand, sku, cover, sortOrder, searchable });
}
records.sort((a, b) => a.sortOrder - b.sortOrder);
await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, `// Generated by tools/build-search-index.mjs. Do not edit.\nexport const searchIndex = ${JSON.stringify(records)} as const;\n`, 'utf8');
console.log(`Built search index with ${records.length} products.`);
